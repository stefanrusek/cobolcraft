from mesh4 import *
IDS=['SHEEP','SHEEP_WOOL','SHEEP_BABY','SHEEP_WOOL_UNDERCOAT','SHEEP_BABY_WOOL']
hdr='''*> Entity models part 4 section 5 (Sheep): the meshes of sheep, sheep_wool, sheep_baby and the undercoat and baby wool ids (5.4), textures and layer rules (5.1, 5.3), setupAnim (5.2), dye colours (5.5), jeb colours (5.6).
*> Entry points for the integrator (inputs; the table programs take IN (16 FLOAT-LONG) and OUT (64 FLOAT-LONG)):
*>   EF4-SHEEP-TEXTURE IN(baby) path(out X(120)); EF4-UNDERCOAT-DRAW IN(invisible, jeb, colour not white, baby) OUT(drawn); EF4-WOOL-DRAW IN(sheared, baby, invisible, glowing) OUT(mode 0 none 1 coloured cut-out 2 outline only, baby model, sub-order);
*>   EF4-DYE-COLOUR IN(ordinal 0..15, texture diffuse RGB) OUT(opaque diffuse ARGB, sheep colour ARGB as an unsigned number); EF4-JEB-COLOUR IN(ageInTicks) OUT(alpha, red, green, blue, packed ARGB);
*>   EF4-SHEEP-ANIM EMM-MODEL state(1 xRot, 2 yRot degrees, 3 walk position, 4 walk speed, 5 headEatPositionScale, 6 headEatAngleScale, 7 ageScale): 5.2.
'''
extra=''' IDENTIFICATION DIVISION.
 PROGRAM-ID. EF4-SHEEP-TEXTURE.
 DATA DIVISION.
 LINKAGE SECTION.
 01 L-IN.
    05 L-I                 FLOAT-LONG OCCURS 16 TIMES.
 01 L-PATH                 PIC X(120).
 PROCEDURE DIVISION USING L-IN L-PATH.
     MOVE "textures/entity/sheep/sheep.png" TO L-PATH
     IF L-I(1) NOT = 0
         MOVE "textures/entity/sheep/sheep_baby.png" TO L-PATH
     END-IF
     GOBACK.
 END PROGRAM EF4-SHEEP-TEXTURE.

 IDENTIFICATION DIVISION.
 PROGRAM-ID. EF4-UNDERCOAT-DRAW.
 DATA DIVISION.
 LINKAGE SECTION.
 01 L-IN.
    05 L-I                 FLOAT-LONG OCCURS 16 TIMES.
 01 L-OUT.
    05 L-O                 FLOAT-LONG OCCURS 64 TIMES.
 PROCEDURE DIVISION USING L-IN L-OUT.
     MOVE 0 TO L-O(1)
     IF L-I(1) = 0 AND (L-I(2) NOT = 0 OR L-I(3) NOT = 0) AND L-I(4) = 0
         MOVE 1 TO L-O(1)
     END-IF
     GOBACK.
 END PROGRAM EF4-UNDERCOAT-DRAW.

 IDENTIFICATION DIVISION.
 PROGRAM-ID. EF4-WOOL-DRAW.
 DATA DIVISION.
 LINKAGE SECTION.
 01 L-IN.
    05 L-I                 FLOAT-LONG OCCURS 16 TIMES.
 01 L-OUT.
    05 L-O                 FLOAT-LONG OCCURS 64 TIMES.
 PROCEDURE DIVISION USING L-IN L-OUT.
     MOVE 0 TO L-O(1) L-O(2) L-O(3)
     IF L-I(2) NOT = 0
         MOVE 1 TO L-O(2)
     END-IF
     IF L-I(1) = 0
         IF L-I(3) = 0
             MOVE 1 TO L-O(1)
             MOVE L-I(2) TO L-O(3)
         ELSE
             IF L-I(4) NOT = 0
                 MOVE 2 TO L-O(1)
             END-IF
         END-IF
     END-IF
     GOBACK.
 END PROGRAM EF4-WOOL-DRAW.

 IDENTIFICATION DIVISION.
 PROGRAM-ID. EF4-DYE-COLOUR.
 DATA DIVISION.
 WORKING-STORAGE SECTION.
 01 WS-RGB                 BINARY-DOUBLE.
 01 WS-R                   BINARY-DOUBLE.
 01 WS-G                   BINARY-DOUBLE.
 01 WS-B                   BINARY-DOUBLE.
 LINKAGE SECTION.
 01 L-IN.
    05 L-I                 FLOAT-LONG OCCURS 16 TIMES.
 01 L-OUT.
    05 L-O                 FLOAT-LONG OCCURS 64 TIMES.
 PROCEDURE DIVISION USING L-IN L-OUT.
     COMPUTE WS-RGB = L-I(2)
     COMPUTE L-O(1) = 4278190080 + WS-RGB
     COMPUTE WS-R = FUNCTION INTEGER(WS-RGB / 65536)
     COMPUTE WS-G = FUNCTION MOD(FUNCTION INTEGER(WS-RGB / 256), 256)
     COMPUTE WS-B = FUNCTION MOD(WS-RGB, 256)
     IF L-I(1) = 0
         MOVE 4293322470 TO L-O(2)
     ELSE
         COMPUTE WS-R = FUNCTION INTEGER(WS-R * 0.75)
         COMPUTE WS-G = FUNCTION INTEGER(WS-G * 0.75)
         COMPUTE WS-B = FUNCTION INTEGER(WS-B * 0.75)
         COMPUTE L-O(2) = 4278190080 + WS-R * 65536 + WS-G * 256 + WS-B
     END-IF
     GOBACK.
 END PROGRAM EF4-DYE-COLOUR.

 IDENTIFICATION DIVISION.
 PROGRAM-ID. EF4-JEB-COLOUR.
 DATA DIVISION.
 WORKING-STORAGE SECTION.
 01 WS-DIFFUSE.
    05 FILLER PIC 9(8) VALUE 16383998.
    05 FILLER PIC 9(8) VALUE 16351261.
    05 FILLER PIC 9(8) VALUE 13061821.
    05 FILLER PIC 9(8) VALUE 3847130.
    05 FILLER PIC 9(8) VALUE 16701501.
    05 FILLER PIC 9(8) VALUE 8439583.
    05 FILLER PIC 9(8) VALUE 15961002.
    05 FILLER PIC 9(8) VALUE 4673362.
    05 FILLER PIC 9(8) VALUE 10329495.
    05 FILLER PIC 9(8) VALUE 1481884.
    05 FILLER PIC 9(8) VALUE 8991416.
    05 FILLER PIC 9(8) VALUE 3949738.
    05 FILLER PIC 9(8) VALUE 8606770.
    05 FILLER PIC 9(8) VALUE 6192150.
    05 FILLER PIC 9(8) VALUE 11546150.
    05 FILLER PIC 9(8) VALUE 1908001.
 01 WS-DIFFUSE-R REDEFINES WS-DIFFUSE.
    05 WS-D                PIC 9(8) OCCURS 16 TIMES.
 01 WS-IN2.
    05 WS-IV               FLOAT-LONG OCCURS 16 TIMES.
 01 WS-OUT2.
    05 WS-OV               FLOAT-LONG OCCURS 64 TIMES.
 01 WS-C0                  BINARY-DOUBLE.
 01 WS-C1                  BINARY-DOUBLE.
 01 WS-I                   BINARY-DOUBLE.
 01 WS-STEP                BINARY-DOUBLE.
 01 WS-T                   FLOAT-LONG.
 01 WS-SH                  BINARY-LONG.
 01 WS-X                   BINARY-DOUBLE.
 01 WS-Y                   BINARY-DOUBLE.
 01 WS-CH                  BINARY-DOUBLE OCCURS 4 TIMES.
 01 WS-K                   BINARY-LONG.
 LINKAGE SECTION.
 01 L-IN.
    05 L-I                 FLOAT-LONG OCCURS 16 TIMES.
 01 L-OUT.
    05 L-O                 FLOAT-LONG OCCURS 64 TIMES.
 PROCEDURE DIVISION USING L-IN L-OUT.
     COMPUTE WS-I = FUNCTION INTEGER(L-I(1))
     COMPUTE WS-STEP = FUNCTION INTEGER(WS-I / 25)
     COMPUTE WS-T = (FUNCTION MOD(WS-I, 25) + (L-I(1) - WS-I)) / 25
     COMPUTE WS-K = FUNCTION MOD(WS-STEP, 16)
     COMPUTE WS-IV(1) = WS-K
     COMPUTE WS-IV(2) = WS-D(WS-K + 1)
     CALL "EF4-DYE-COLOUR" USING WS-IN2 WS-OUT2
     COMPUTE WS-C0 = WS-OV(2)
     COMPUTE WS-K = FUNCTION MOD(WS-STEP + 1, 16)
     COMPUTE WS-IV(1) = WS-K
     COMPUTE WS-IV(2) = WS-D(WS-K + 1)
     CALL "EF4-DYE-COLOUR" USING WS-IN2 WS-OUT2
     COMPUTE WS-C1 = WS-OV(2)
     MOVE 0 TO L-O(5)
     PERFORM VARYING WS-K FROM 1 BY 1 UNTIL WS-K > 4
         COMPUTE WS-SH = 4 - WS-K
         COMPUTE WS-X = FUNCTION MOD(FUNCTION INTEGER(WS-C0 / (256 ** WS-SH)), 256)
         COMPUTE WS-Y = FUNCTION MOD(FUNCTION INTEGER(WS-C1 / (256 ** WS-SH)), 256)
         COMPUTE WS-CH(WS-K) = WS-X + FUNCTION INTEGER(WS-T * (WS-Y - WS-X))
         MOVE WS-CH(WS-K) TO L-O(WS-K)
         COMPUTE L-O(5) = L-O(5) + WS-CH(WS-K) * (256 ** WS-SH)
     END-PERFORM
     GOBACK.
 END PROGRAM EF4-JEB-COLOUR.

 IDENTIFICATION DIVISION.
 PROGRAM-ID. EF4-SHEEP-ANIM.
 DATA DIVISION.
 WORKING-STORAGE SECTION.
 01 WS-NAME                PIC X(24).
 01 WS-P                   BINARY-LONG.
 01 WS-QI.
    05 WS-QV               FLOAT-LONG OCCURS 16 TIMES.
 LINKAGE SECTION.
 COPY CLEMM.
 01 L-IN.
    05 L-I                 FLOAT-LONG OCCURS 16 TIMES.
 PROCEDURE DIVISION USING EMM-MODEL L-IN.
     CALL "EF4-QUAD-POSE" USING EMM-MODEL L-IN
     MOVE "head" TO WS-NAME
     CALL "EMM-FIND" USING EMM-MODEL WS-NAME WS-P
     COMPUTE MM-CY(WS-P) = MM-CY(WS-P) + L-I(5) * 9 * L-I(7)
     MOVE L-I(6) TO MM-CXROT(WS-P)
     GOBACK.
 END PROGRAM EF4-SHEEP-ANIM.
'''
