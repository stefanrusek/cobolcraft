def item_spine(path):
    lines = read_lines(path)
    start = next(i for i, l in enumerate(lines) if l.startswith("### 11.6"))
    inside, items = False, {}
    for line in lines[start:]:
        if line.startswith("```"):
            if inside:
                break
            inside = True
            continue
        if inside:
            for i, k in re.findall(r"(\d+) ([a-z_0-9]+)", line):
                items[int(i)] = k
    return items


FLAG_COMPONENTS = ["food", "consumable", "cooking_fuel", "tool", "weapon", "equippable", "enchantable", "damage_resistant",
                   "compostable", "container", "fireworks", "unbreakable", "jukebox_playable", "repairable"]


def build_items(docs, block_ids):
    parts = doc_files(docs, "25-")
    if len(parts) != 9:
        raise Problem("expected 9 item registry documents (parts 1 to 8 and x1), found %d" % len(parts))
    problems = []
    last8 = [p for p in parts if "item-registry-8" in p][0]
    spine = item_spine(last8)
    stated = None
    for table in parse_tables(read_lines(last8)):
        if table["h"] == ["#", "check", "result"]:
            for r in table["rows"]:
                if r[1].startswith("Items expanded from collections"):
                    stated = int(re.findall(r"total (\d+)", r[2])[-1])
    if stated is None:
        problems.append("25 part 8 §13 check V2 states no item total")
    elif stated != len(spine):
        problems.append("Items (25 part 8 V2): documents state %d, generated %d" % (stated, len(spine)))
    if sorted(spine) != list(range(len(spine))):
        problems.append("item ids are not contiguous from 0")
    attrs = {}
    for path in parts:
        for table in parse_tables(read_lines(path)):
            h = table["h"]
            ki = col_index(h, "key")
            ii = col_index(h, "id", "registry id")
            if ki is None or ii is None:
                continue
            ci = next((i for i, x in enumerate(h) if x.startswith("class") or x == "builder"), None)
            si = col_index(h, "max stack")
            xi = next((i for i, x in enumerate(h) if x.startswith("components") or x in ("extra", "extra components")), None)
            for r in table["rows"]:
                if len(r) <= max(ki, ii) or not re.fullmatch(r"\d+", r[ii]):
                    continue
                key = r[ki]
                if spine.get(int(r[ii])) != key:
                    continue
                slot = attrs.setdefault(int(r[ii]), {})
                if ci is not None and ci < len(r):
                    slot.setdefault("class", class_name(r[ci]))
                if si is not None and si < len(r) and re.fullmatch(r"\d+", r[si]):
                    slot.setdefault("stack", r[si])
                if xi is not None and xi < len(r) and r[xi] not in ("none", "-"):
                    slot.setdefault("comp", r[xi])
    rows, no_stack, no_class = [], 0, 0
    for i in sorted(spine):
        a = attrs.get(i, {})
        comp = a.get("comp", "")
        damage = re.search(r"max_damage\W{0,12}?(\d+)", comp)
        flags = " ".join(c for c in FLAG_COMPONENTS if re.search(r"\b%s\b" % c, comp))
        no_stack += "stack" not in a
        no_class += "class" not in a
        link = str(block_ids[spine[i]]) if spine[i] in block_ids else ""
        rows.append([str(i), spine[i], a.get("class", ""), link, a.get("stack", ""), damage.group(1) if damage else "",
                     flags, ascii_text(comp)[:100]])
    rows = [[ascii_text(v) for v in r] for r in rows]
    cols = ["ID", "KEY", "CLASS", "BLOCK", "STACK", "MAXDAMAGE", "FLAGS", "COMPONENTS"]
    text = emit("ITEM", "Items of docs/protocol/25-item-registry-1..8 and x1 (11.6 key list spine). BLOCK is the id of "
                "the block of the same key (24 part 4 section 3 item 3); COMPONENTS is the first 100 characters of "
                "the components beyond the common set.", cols, rows)
    return {"items.cpy": text}, problems, {"items": len(spine), "items without max stack": no_stack,
                                          "items without class": no_class}


# ---------------------------------------------------------------- static ids, entities, tags (46, 21, 24-1)

STATED_ENTRIES = re.compile(r"`([a-z_]+)`, (\d+) entries")


def registry_sections(path):
    """(registry, stated count, tables) for every place of 46 that names a registry with its entry count."""
    lines = read_lines(path)
    marks = []
    for n, line in enumerate(lines):
        if line.startswith("#") or STATED_ENTRIES.search(line):
            m = STATED_ENTRIES.search(line)
            marks.append((n, m.group(1) if m else None, int(m.group(2)) if m else None))
    found = []
    for k, (n, name, count) in enumerate(marks):
        if name is None:
            continue
        end = marks[k + 1][0] if k + 1 < len(marks) else len(lines)
        found.append((name, count, parse_tables(lines[n:end])[:1]))
    return found


def collect_entries(tables):
    entries = []
    for t in tables:
        h = t["h"]
        for i, x in enumerate(h):
            if x in ("id", "stat type id") and i + 1 < len(h) and h[i + 1] == "key":
                for r in t["rows"]:
                    if i + 1 < len(r) and re.fullmatch(r"\d+", r[i]):
                        entries.append((int(r[i]), r[i + 1]))
    return entries


def build_static_ids(docs):
    path = os.path.join(docs, "46-registry-ids.md")
    problems, rows, counts = [], [], {}
    for name, stated, tables in registry_sections(path):
        entries = collect_entries(tables)
        ids = sorted(e[0] for e in entries)
        if len(entries) != stated:
            problems.append("46 registry %s: documents state %d entries, generated %d" % (name, stated, len(entries)))
        if ids != list(range(len(ids))):
            problems.append("46 registry %s: ids are not 0 to n-1 without gaps" % name)
        counts[name] = len(entries)
        rows.extend([name, str(i), k] for i, k in sorted(entries))
    # The stat types are a table without an entry count in its heading: "the 9 stat types first".
    lines = read_lines(path)
    text = "\n".join(lines)
    m = re.search(r"the (\d+) stat types", text)
    stat = []
    for t in parse_tables(lines):
        if t["h"][:2] == ["stat type id", "key"]:
            stat = [(int(r[0]), r[1]) for r in t["rows"]]
    if not m:
        problems.append("46 §7 states no stat type count")
    elif int(m.group(1)) != len(stat):
        problems.append("46 registry stat_type: documents state %s entries, generated %d" % (m.group(1), len(stat)))
    counts["stat_type"] = len(stat)
    rows.extend(["stat_type", str(i), k] for i, k in stat)
    rows = [[ascii_text(v) for v in r] for r in rows]
    text = emit("STATIC", "Static registry ids of docs/protocol/46-registry-ids.md: registry name, protocol id, key.",
                ["REGISTRY", "ID", "KEY"], rows)
    counts["static registries"] = len({r[0] for r in rows})
    counts["static registry rows"] = len(rows)
    return {"staticids.cpy": text}, problems, counts


def build_entities(docs):
    path = [p for p in doc_files(docs, "21-")][0]
    lines = read_lines(path)
    problems = []
    stated = None
    for line in lines:
        m = re.search(r"The registry has (\d+) entity types", line)
        if m:
            stated = int(m.group(1))
            break
    rows = []
    for t in parse_tables(lines):
        if t["h"][:4] == ["id", "key", "class", "category"]:
            si = col_index(t["h"], "size (w x h)")
            for r in t["rows"]:
                if re.fullmatch(r"\d+", r[0]):
                    rows.append([r[0], r[1], r[si] if si is not None and si < len(r) else "", r[3]])
    if stated is None:
        problems.append("21 §2 states no entity type count")
    elif stated != len(rows):
        problems.append("entity types: documents state %d, generated %d" % (stated, len(rows)))
    if [int(r[0]) for r in rows] != list(range(len(rows))):
        problems.append("21 §2 entity ids are not 0 to n-1 without gaps")
    # 46 §11 notable ids must agree with 21 §2.
    keys = {int(r[0]): r[1] for r in rows}
    for i, k in ((101, "pig"), (72, "item"), (159, "player"), (160, "fishing_bobber"), (28, "copper_golem"),
                 (59, "happy_ghast"), (108, "splash_potion"), (109, "lingering_potion")):
        if keys.get(i) != k:
            problems.append("46 §11 says entity %d is %s, 21 §2 gives %s" % (i, k, keys.get(i)))
    rows = [[ascii_text(v) for v in r] for r in rows]
    text = emit("ENTITY", "Entity types of docs/protocol/21 section 2 (ids checked against 46 section 11): id, key, "
                "size (width x height), category.", ["ID", "KEY", "SIZE", "CATEGORY"], rows)
    return {"entities.cpy": text}, problems, {"entity types": len(rows)}


def build_tags(docs):
    path = doc_files(docs, "24-")[0]
    lines = read_lines(path)
    start = next(i for i, l in enumerate(lines) if l.startswith("### 12.3"))
    end = next(i for i in range(start + 1, len(lines)) if lines[i].startswith("## "))
    groups, current, problems = [], None, []
    for line in lines[start + 1:end]:
        if not line.strip():
            continue
        head = re.match(r"(Read from .*?\((\d+)[;)].*|Seventeen other .*)", line)
        if head:
            stated = int(head.group(2)) if head.group(2) else 17
            source = "ItemOnly" if line.startswith("Seventeen") else (
                "BlockTags" if "`BlockTags`" in line.split("(")[0] else "BlockItemTags")
            current = {"source": source, "stated": stated, "keys": []}
            if source == "ItemOnly":
                current["keys"].extend(re.findall(r"`([a-z_0-9/]+)`", line.split(":", 1)[1]))
            groups.append(current)
        elif current is not None:
            current["keys"].extend(re.findall(r"`([a-z_0-9/]+)`", line))
    rows = []
    for g in groups:
        if len(g["keys"]) != g["stated"]:
            problems.append("24 part 1 §12.3 group %s: documents state %d tag names, generated %d" %
                            (g["source"], g["stated"], len(g["keys"])))
        rows.extend([k, g["source"]] for k in g["keys"])
    if len(groups) != 3:
        problems.append("24 part 1 §12.3: expected 3 tag name groups, found %d" % len(groups))
    text = emit("TAGNAME", "Tag names read by code, 24 part 1 section 12.3: key path under minecraft:, source class "
                "(BlockTags 218, BlockItemTags 66, ItemOnly 17).", ["KEY", "SOURCE"], [[ascii_text(a), b] for a, b in rows])
    return {"tagnames.cpy": text}, problems, {"tag names": len(rows)}


