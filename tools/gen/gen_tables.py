# ---------------------------------------------------------------- markdown helpers

def clean(cell):
    return cell.strip().strip("`").strip()


def split_row(line):
    return [clean(c) for c in line.strip().strip("|").split("|")]


def parse_tables(lines):
    """Tables of a list of lines: dicts with lower-case header `h`, rows `rows`, first line index `at`."""
    out = []
    cur = None
    for number, line in enumerate(lines):
        if line.startswith("|"):
            cells = split_row(line)
            if cur is None:
                cur = {"h": [c.lower() for c in cells], "rows": [], "at": number}
            elif all(re.fullmatch(r":?-+:?", c) for c in cells if c):
                pass
            else:
                cur["rows"].append(cells)
        elif cur is not None:
            out.append(cur)
            cur = None
    if cur is not None:
        out.append(cur)
    return out


def read_lines(path):
    with open(path, encoding="utf-8") as handle:
        return handle.read().split("\n")


def doc_files(docs, prefix):
    names = sorted(n for n in os.listdir(docs) if n.startswith(prefix) and n.endswith(".md"))
    return [os.path.join(docs, n) for n in names]


def ascii_text(text):
    text = text.replace("→", "->").replace("–", "-").replace("—", "-").replace("×", "x")
    text = text.encode("ascii", "replace").decode("ascii").replace('"', "'")
    return re.sub(r"\s+", " ", text).strip()


def first_int(text):
    match = re.search(r"\d[\d,\s]*", text)
    return int(re.sub(r"\D", "", match.group(0))) if match else None


# ---------------------------------------------------------------- fixed-width emitter

def emit(prefix, comment, columns, rows, extra=(), minimum=None):
    """Copybook text for a table. `columns` is a list of names; `rows` are lists of strings. `minimum` gives the
    widths of the contract copybook (contract/copy/CONTENT.cpy), which a column keeps when its content is shorter."""
    widths = [max([len(r[i]) for r in rows] + [(minimum or [1] * len(columns))[i]]) for i in range(len(columns))]
    width = sum(widths)
    text = "".join("".join(v.ljust(w) for v, w in zip(r, widths)) for r in rows)
    pad = (-len(text)) % CHUNK
    text += " " * pad
    out = ["*> GENERATED by tools/gen/gen_tables.py from docs/protocol. Do not edit by hand.", "*> " + comment]
    out.append("*> Row = fixed-width text columns, concatenated; row N starts at byte (N - 1) * ROW-WIDTH + 1.")
    out.append("01 GEN-%s-ROWS PIC 9(6) VALUE %d." % (prefix, len(rows)))
    out.append("01 GEN-%s-ROW-WIDTH PIC 9(4) VALUE %d." % (prefix, width))
    offset = 0
    for name, w in zip(columns, widths):
        out.append("78 GEN-%s-OFF-%s VALUE %d." % (prefix, name, offset))
        out.append("78 GEN-%s-W-%s VALUE %d." % (prefix, name, w))
        offset += w
    for line in extra:
        out.append(line)
    out.append("01 GEN-%s-DATA." % prefix)
    for i in range(0, len(text), CHUNK):
        out.append('    05 FILLER PIC X(%d) VALUE "%s".' % (CHUNK, text[i:i + CHUNK]))
    if not text:
        out.append('    05 FILLER PIC X(1) VALUE " ".')
    return "\n".join(out) + "\n"


