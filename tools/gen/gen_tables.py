"""Registry copybook generator and drift gate (contracts/test-harness-delta.md `make gate-tables`).

usage: gen_tables.py (--check | --write) [--out DIR] [--docs DIR]

`--write` regenerates the registry copybooks into DIR (default content/copy/gen/) from the markdown tables of
docs/protocol (24 block registry parts 1 to 8, 25 item registry parts 1 to 8 and x1, 46 registry ids, 21 entity
types, 22 accepted jars, README). `--check` regenerates into a scratch directory, compares every file byte for
byte with DIR and exits 1 naming each file that differs, is missing or is unexpected. Both modes print the counts
they generated and exit 1 when a count differs from the count the documents state in their validation sections
(24 part 8 §11.1, 25 part 8 §13 V2, 46 headings and §11, 24 part 1 §12.3), so a lost document row is a failure.

Output layout (data-model §2, research R3): every table is a fixed-width text row per record, concatenated and
cut into `PIC X(400) VALUE "..."` rows. The copybook states the row count, the row width and the offset and width
of every column as level-78 constants. Test infrastructure, stdlib only. Values are copied from the documents;
a column the documents do not give for a row stays blank (spaces).
"""
