def build_jar(docs):
    problems = []
    readme = read_lines(os.path.join(docs, "README.md"))
    facts = {}
    for t in parse_tables(readme):
        if t["h"] == ["item", "value"]:
            for r in t["rows"]:
                facts[r[0]] = r[1]
    sha = re.search(r"SHA-256 `?([0-9a-f]{64})", facts.get("Source artifact", ""))
    if not sha:
        problems.append("README has no Source artifact SHA-256")
    jar = [l for l in read_lines(os.path.join(docs, "22-extraction-tool.md"))]
    start = next(i for i, l in enumerate(jar) if l.startswith("### 4.1"))
    row = None
    for t in parse_tables(jar[start:start + 20]):
        if t["h"][:3] == ["version id", "size (bytes)", "sha-256"]:
            if len(t["rows"]) != 1:
                problems.append("22 §4.1 has %d accepted jar rows, expected 1" % len(t["rows"]))
            row = t["rows"][0]
    if row is None:
        raise Problem("22 §4.1 accepted-jar table not found")
    if sha and row[2] != sha.group(1):
        problems.append("README SHA-256 differs from the 22 §4.1 row")
    if row[3] != facts.get("World data version") or row[4] != facts.get("Protocol version"):
        problems.append("README world or protocol version differs from the 22 §4.1 row")
    version = re.search(r"minecraft-([0-9.]+)-client", facts.get("Source artifact", ""))
    if not version or version.group(1) != row[0]:
        problems.append("README artifact version differs from the 22 §4.1 version id")
    cells = [row[0], str(first_int(row[1])), row[2], row[3], row[4], row[5], row[6]]
    text = emit("ACCEPTEDJAR", "The accepted-jar row of docs/protocol/22 section 4.1 (README Source artifact): version "
                "id, size in bytes, SHA-256, world version, protocol version, resource format, data format.",
                ["VERSION", "SIZE", "SHA256", "WORLD", "PROTOCOL", "RESOURCE", "DATA"], [[ascii_text(c) for c in cells]])
    return {"acceptedjar.cpy": text}, problems, {"accepted jars": 1}


# ---------------------------------------------------------------- driver

def build(docs):
    """(files, problems, counts) for the documents in `docs`."""
    files, problems, counts = {}, [], {}
    blocks, p, c, block_ids = build_blocks(docs)
    files.update(blocks), problems.extend(p), counts.update(c)
    for builder in (lambda d: build_items(d, block_ids), build_static_ids, build_entities, build_tags, build_jar):
        f, p, c = builder(docs)
        files.update(f), problems.extend(p), counts.update(c)
    return files, problems, counts


def generate(directory, docs=DEFAULT_DOCS):
    """Write every generated file into `directory`; return (names, problems, counts)."""
    os.makedirs(directory, exist_ok=True)
    files, problems, counts = build(docs)
    for name, text in files.items():
        with open(os.path.join(directory, name), "w", encoding="ascii", newline="\n") as handle:
            handle.write(text)
    return sorted(files), problems, counts


def listing(directory):
    """Sorted names of the files under `directory` (empty when it does not exist)."""
    found = []
    for root, _, names in os.walk(directory):
        found.extend(os.path.relpath(os.path.join(root, name), directory) for name in names if name not in KEEP)
    return sorted(found)


def read(path):
    with open(path, "rb") as handle:
        return handle.read()


def drift(expected_dir, actual_dir):
    """Names of the files of the two directories that differ, are missing or are unexpected."""
    differing = []
    for name in sorted(set(listing(expected_dir)) | set(listing(actual_dir))):
        expected = os.path.join(expected_dir, name)
        actual = os.path.join(actual_dir, name)
        if not (os.path.isfile(expected) and os.path.isfile(actual) and read(expected) == read(actual)):
            differing.append(name)
    return differing


def report(counts, problems):
    for name in sorted(counts):
        print("COUNT %s %d" % (name, counts[name]))
    for problem in problems:
        print("PROBLEM " + problem)


def main(argv):
    parser = argparse.ArgumentParser(description="Generate or check the registry copybooks.")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="fail when DIR differs from a fresh regeneration")
    mode.add_argument("--write", action="store_true", help="regenerate DIR")
    parser.add_argument("--out", default=DEFAULT_OUT, help="generated directory (default content/copy/gen)")
    parser.add_argument("--docs", default=DEFAULT_DOCS, help="documents directory (default docs/protocol)")
    arguments = parser.parse_args(argv)
    try:
        if arguments.write:
            _, problems, counts = generate(arguments.out, arguments.docs)
            report(counts, problems)
            return 1 if problems else 0
        with tempfile.TemporaryDirectory(prefix="gen-tables-") as scratch:
            _, problems, counts = generate(scratch, arguments.docs)
            differing = drift(scratch, arguments.out)
    except Problem as error:
        print("PROBLEM " + str(error))
        return 1
    report(counts, problems)
    for name in differing:
        print("DRIFT " + name)
    print("gen_tables: %d differing files, %d count problems" % (len(differing), len(problems)))
    return 1 if differing or problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
