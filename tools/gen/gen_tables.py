def norm_tool(value):
    value = value.strip().lower()
    if value in ("yes", "req", "true"):
        return "yes"
    if value in ("no", "false"):
        return "no"
    return ""


def class_name(text):
    return re.split(r"[ (]", text.strip(), maxsplit=1)[0]


def read_appendix(path):
    for table in parse_tables(read_lines(path)):
        h = table["h"]
        if h[:1] == ["field"] and len(h) == 6 and "first state id" in h:
            return table["rows"]
    raise Problem("24 part 8 Appendix A (all 911 fields) not found")


def expand_fields(appendix, weathering_keys):
    """List of block dicts (id, key, first, states, field) from Appendix A and the collection key rules."""
    blocks = []
    for row in appendix:
        field, name, ids, first, states, count = row[0], row[1], row[2], int(row[3]), int(row[4]), int(row[5])
        low, high = (int(x) for x in ids.split("-")) if "-" in ids else (int(ids), int(ids))
        if high - low + 1 != count:
            raise Problem("Appendix A field %s: id range %s does not hold %d blocks" % (field, ids, count))
        per = states // count
        for n in range(count):
            blocks.append({"id": low + n, "field": int(field), "fname": name, "first": first + n * per,
                           "states": per, "member": n, "count": count, "key": None})
    return blocks


def collect_block_keys(docs):
    """Map block id -> registry key from every per-part table that gives both (parts 1 to 8)."""
    keys = {}
    for path in doc_files(docs, "24-"):
        for table in parse_tables(read_lines(path)):
            h = table["h"]
            ki = col_index(h, "key", "registry key", "key (block)")
            ii = col_index(h, "block id", "id")
            if ki is None or ii is None or ii == ki:
                continue
            for r in table["rows"]:
                if len(r) > max(ki, ii) and re.fullmatch(r"\d+", r[ii]):
                    key = r[ki].replace("minecraft:", "")
                    if re.fullmatch(r"[a-z_0-9]+", key):
                        keys.setdefault(int(r[ii]), key)
    return keys


def weathering_table(path):
    """Field -> four weathering keys from 24 part 8 §7.3; the waxed keys are `waxed_` + each."""
    out = {}
    for table in parse_tables(read_lines(path)):
        h = table["h"]
        if h[:2] == ["field", "ids"] and "keys of the four weathering blocks" in h:
            for r in table["rows"]:
                out[int(r[0])] = [k.strip() for k in r[2].split(",")]
    return out


def assign_keys(blocks, idkey, weathering):
    """Fill block['key']; return the list of problems."""
    problems = []
    for b in blocks:
        if b["id"] in idkey:
            b["key"] = idkey[b["id"]]
        elif b["count"] == 1:
            b["key"] = b["fname"]
        elif b["field"] in weathering:
            four = weathering[b["field"]]
            b["key"] = four[b["member"]] if b["member"] < 4 else "waxed_" + four[b["member"] - 4]
        elif b["count"] == 16:
            b["key"] = "%s_%s" % (DYES[b["member"]], DYE_SUFFIX.get(b["fname"], b["fname"]))
        if not b["key"]:
            problems.append("block id %d has no key" % b["id"])
    return problems


def collect_block_attrs(docs, blocks):
    """Attributes per block id, first table to give a value wins. Returns (attrs, field-level fallback count)."""
    by_key = {b["key"]: b for b in blocks}
    by_field = {}
    for b in blocks:
        by_field.setdefault(b["fname"], []).append(b)
    by_fieldno = {}
    for b in blocks:
        by_fieldno.setdefault(b["field"], []).append(b)
    attrs = {b["id"]: {} for b in blocks}

    def put(targets, values, whole_field):
        for b in targets:
            slot = attrs[b["id"]]
            for k, v in values.items():
                if v == "" or (k in ("map", "flags", "default", "props") and whole_field and b["count"] > 1):
                    continue
                slot.setdefault(k, v)

    for path in doc_files(docs, "24-"):
        for table in parse_tables(read_lines(path)):
            h = table["h"]
            cols = {k: col_index(h, *names) for k, names in ATTR_COLUMNS.items()}
            hr = col_index(h, "h / r")
            if cols["hardness"] is None and hr is None:
                continue
            ki = col_index(h, "key", "registry key", "key (block)")
            fi = col_index(h, "field")
            oi = col_index(h, "ord(s) and key(s)")
            idi = col_index(h, "id", "block id")
            for r in table["rows"]:
                values = {}
                for k, i in cols.items():
                    if i is not None and i < len(r):
                        values[k] = r[i]
                if hr is not None and hr < len(r) and "/" in r[hr]:
                    values["hardness"], values["resist"] = (x.strip() for x in r[hr].split("/", 1))
                if "class" in values:
                    values["class"] = class_name(values["class"])
                if "tool" in values:
                    values["tool"] = norm_tool(values["tool"])
                elif "needstool" in values.get("flags", ""):
                    values["tool"] = "yes"
                if values.get("flags", "") in ("-",):
                    values["flags"] = ""
                if values.get("props", "") in ("-",):
                    values["props"] = ""
                if "default" in values and not re.fullmatch(r"\d+", values["default"]):
                    del values["default"]
                targets, whole = [], False
                if oi is not None:
                    for k in re.findall(r"`([a-z_0-9]+)`", table_raw(path, table, r)):
                        if k in by_key:
                            targets.append(by_key[k])
                    if not targets:
                        continue
                    # Part 2 defaults stated in the column notes: blank instrument is HARP, blank sound is STONE.
                    values.setdefault("instrument", "")
                    if values["instrument"] == "":
                        values["instrument"] = "HARP"
                    if values.get("sound", "") == "":
                        values["sound"] = "STONE"
                elif ki is not None and ki < len(r) and r[ki].replace("minecraft:", "") in by_key:
                    targets = [by_key[r[ki].replace("minecraft:", "")]]
                    if targets[0]["count"] > 1 and targets[0]["member"] == 0:
                        targets = by_field.get(targets[0]["fname"], targets)
                        whole = True
                elif fi is not None and fi < len(r):
                    name = re.sub(r"\s*\(\d+ blocks?\)", "", r[fi]).lower()
                    if re.fullmatch(r"\d+", name) and int(name) in by_fieldno:
                        targets = by_fieldno[int(name)]
                        whole = len(targets) > 1
                    elif name in by_field:
                        targets = by_field[name]
                        whole = len(targets) > 1
                    elif name in by_key:
                        targets = [by_key[name]]
                if not targets:
                    continue
                put(targets, values, whole)
    return attrs


_RAW_CACHE = {}


def table_raw(path, table, row):
    """The first cell of a part 2 §5 row with its backticks (clean() removed them)."""
    key = path
    if key not in _RAW_CACHE:
        _RAW_CACHE[key] = read_lines(path)
    for line in _RAW_CACHE[key]:
        if line.startswith("|") and clean(line.strip().strip("|").split("|")[0]) == row[0]:
            return line.strip().strip("|").split("|")[0]
    return row[0]


def property_rows(docs):
    """Unique (name, value list) pairs from the property definition tables of 24 parts 1 to 8."""
    seen = {}
    spec = {1: [("values in order", 1)], 2: [("values in order", 1)], 3: [("values in order", 0)],
            4: [("type and values", 1)], 5: [("values in order", 0)], 6: [("values in order", 1)],
            7: [("type and values in order", 0)], 8: [("values in order", 1)]}
    for part, path in enumerate(doc_files(docs, "24-"), 1):
        for table in parse_tables(read_lines(path)):
            h = table["h"]
            vi = col_index(h, "values in order", "type and values", "type and values in order")
            ni = col_index(h, "name", "property (name)", "property name", "name (property key)")
            if vi is None or ni is None or ni == vi:
                continue
            for r in table["rows"]:
                if len(r) <= max(vi, ni):
                    continue
                match = re.match(r"[a-z_0-9]+", r[ni])
                if not match:
                    continue
                name, values = match.group(0), ascii_text(r[vi])
                seen.setdefault((name, values), True)
    return sorted(seen)


def build_blocks(docs):
    parts = doc_files(docs, "24-")
    if len(parts) != 8:
        raise Problem("expected 8 block registry documents, found %d" % len(parts))
    appendix = read_appendix(parts[7])
    blocks = expand_fields(appendix, None)
    problems = assign_keys(blocks, collect_block_keys(docs), weathering_table(parts[7]))
    attrs = collect_block_attrs(docs, blocks)
    stated = {}
    for table in parse_tables(read_lines(parts[7])):
        if table["h"][:2] == ["quantity", "value"] and len(table["h"]) == 3:
            for r in table["rows"]:
                stated[r[0]] = first_int(r[1])
    stats = {"blocks": len(blocks), "states": sum(b["states"] for b in blocks), "fields": len(appendix)}
    for label, got in (("Registered blocks", stats["blocks"]), ("Block states", stats["states"]),
                       ("Fields of `Blocks` that are blocks", stats["fields"])):
        want = stated.get(label.replace("`", "")) or stated.get(label)
        if want is None:
            want = next((v for k, v in stated.items() if k.startswith(label.split(" of")[0])), None)
        if want is None:
            problems.append("24 part 8 §11.1 states no '%s'" % label)
        elif want != got:
            problems.append("%s: documents state %d, generated %d" % (label, want, got))
    rows = []
    blanks = {k: 0 for k in ("hardness", "default", "props", "map", "sound")}
    ids = sorted(blocks, key=lambda b: b["id"])
    for b in ids:
        a = attrs[b["id"]]
        for k in blanks:
            if not a.get(k):
                blanks[k] += 1
        rows.append([str(b["id"]), b["key"], a.get("class", ""), a.get("props", ""), str(b["states"]),
                     str(b["first"]), a.get("default", ""), a.get("hardness", ""), a.get("resist", ""),
                     a.get("tool", ""), a.get("light", ""), a.get("map", ""), a.get("sound", ""),
                     a.get("push", ""), a.get("instrument", ""), a.get("flags", "")])
    rows = [[ascii_text(v) for v in r] for r in rows]
    cols = ["ID", "KEY", "CLASS", "PROPS", "STATES", "FIRST", "DEFAULT", "HARDNESS", "BLAST", "TOOL", "LIGHT",
            "MAPCOLOR", "SOUND", "PUSH", "INSTRUMENT", "FLAGS"]
    text = emit("BLOCK", "Blocks of docs/protocol/24-block-registry-1..8 (Appendix A spine, per-part rows). "
                "State id of block B state index S = FIRST + S (24 part 1 section 3).", cols, rows)
    prows = [[n, v] for n, v in property_rows(docs)]
    ptext = emit("BLOCKPROP", "Block property definitions (name, value list) of 24 parts 1 to 8; one row per distinct "
                 "(name, values) text.", ["NAME", "VALUES"], prows)
    return {"blocks.cpy": text, "blockprops.cpy": ptext}, problems, \
        {"blocks": stats["blocks"], "block states": stats["states"], "block properties": len(prows),
         "blocks without hardness": blanks["hardness"], "blocks without default state": blanks["default"],
         "blocks without property list": blanks["props"], "blocks without map colour": blanks["map"],
         "blocks without sound": blanks["sound"]}, {b["key"]: b["id"] for b in blocks}


