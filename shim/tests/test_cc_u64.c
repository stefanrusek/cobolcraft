#define COUNT(t) (sizeof(t) / sizeof((t)[0]))

static void run_pairs(const char *name, const pair_case *t, size_t n, void (*f)(const uint64_t *, const uint64_t *, uint64_t *)) {
    int bad = 0;
    for (size_t i = 0; i < n; i++) {
        uint64_t a = t[i].a, b = t[i].b, r = 0;
        f(&a, &b, &r);
        if (r != t[i].want) bad++;
    }
    tl_int(name, 0, bad);
}

static void run_shifts(const char *name, const shift_case *t, size_t n, void (*f)(const uint64_t *, const int32_t *, uint64_t *)) {
    int bad = 0;
    for (size_t i = 0; i < n; i++) {
        uint64_t a = t[i].a, r = 0;
        int32_t c = t[i].n;
        f(&a, &c, &r);
        if (r != t[i].want) bad++;
    }
    tl_int(name, 0, bad);
}

